from datetime import UTC, datetime, timedelta, timezone

import pytest

from access_node_compose_api.mapping import Resolution
from access_node_compose_api.snapshot import Snapshot, format_timestamp

from .conftest import COMMIT, NOW, TREE

CHART = "ionos_sbx/marketplace/access-node"


def build(resolution: Resolution, generated_at: datetime = NOW) -> Snapshot:
    return Snapshot.build(
        resolution=resolution,
        chart_path=CHART,
        gitops_commit=COMMIT,
        tree_hash=TREE,
        generated_at=generated_at,
    )


def test_body_format_without_missing():
    resolution = Resolution(images=(("A_IMAGE", "a:1"), ("B_IMAGE", "b:2")), missing=())
    assert build(resolution).body.decode() == (
        "# Generated by access-node-compose-api from dome-gitops\n"
        f"# chart: {CHART}\n"
        f"# gitops-commit: {COMMIT}\n"
        "# generated-at: 2026-11-06T10:15:00Z\n"
        "A_IMAGE=a:1\n"
        "B_IMAGE=b:2\n"
    )


def test_body_lists_missing_keys():
    resolution = Resolution(images=(("A_IMAGE", "a:1"),), missing=("B_IMAGE", "C_IMAGE"))
    lines = build(resolution).body.decode().splitlines()
    assert lines[4] == "# missing: B_IMAGE C_IMAGE"
    assert lines[5:] == ["A_IMAGE=a:1"]


def test_body_is_compatible_with_env_parsing():
    resolution = Resolution(images=(("A_IMAGE", "repo/a@sha256:abc"),), missing=("B_IMAGE",))
    body = build(resolution).body.decode()
    parsed = dict(
        line.split("=", 1) for line in body.splitlines() if line and not line.startswith("#")
    )
    assert parsed == {"A_IMAGE": "repo/a@sha256:abc"}


@pytest.mark.parametrize("image", ["a:1\nEVIL=x", "a b", "", "a#1", "a=1"])
def test_invalid_image_is_rejected(image):
    with pytest.raises(ValueError, match="invalid image"):
        build(Resolution(images=(("A_IMAGE", image),), missing=()))


def test_etag_is_quoted_and_deterministic():
    resolution = Resolution(images=(("A_IMAGE", "a:1"),), missing=())
    first, second = build(resolution), build(resolution)
    assert first.etag == second.etag
    assert first.etag.startswith('"') and first.etag.endswith('"')
    assert build(resolution, NOW + timedelta(seconds=1)).etag != first.etag


def test_timestamp_is_converted_to_utc():
    rome = timezone(timedelta(hours=1))
    assert format_timestamp(datetime(2026, 11, 6, 11, 15, tzinfo=rome)) == "2026-11-06T10:15:00Z"
    assert format_timestamp(datetime(2026, 11, 6, 10, 15, tzinfo=UTC)) == "2026-11-06T10:15:00Z"


def test_naive_timestamp_is_rejected():
    with pytest.raises(ValueError):
        format_timestamp(datetime(2026, 11, 6, 10, 15))
