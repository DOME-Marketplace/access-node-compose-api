"""Immutable snapshot of the versions served by the API."""

import hashlib
import re
from dataclasses import dataclass
from datetime import UTC, datetime

from .mapping import Resolution

# An image reference is a single token: no whitespace, no '#', no '='.
# Anything else would corrupt the KEY=value format read by the client.
_IMAGE_RE = re.compile(r"[^\s#=]+")


def format_timestamp(value: datetime) -> str:
    """Format an aware datetime as UTC ISO 8601 with a trailing 'Z'."""
    if value.tzinfo is None:
        raise ValueError("timestamp must be timezone-aware")
    return value.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


@dataclass(frozen=True)
class Snapshot:
    body: bytes
    etag: str
    gitops_commit: str
    tree_hash: str
    generated_at: datetime
    missing: tuple[str, ...]

    @classmethod
    def build(
        cls,
        *,
        resolution: Resolution,
        chart_path: str,
        gitops_commit: str,
        tree_hash: str,
        generated_at: datetime,
    ) -> "Snapshot":
        body = render_body(
            resolution=resolution,
            chart_path=chart_path,
            gitops_commit=gitops_commit,
            generated_at=generated_at,
        ).encode("utf-8")
        etag = '"' + hashlib.sha256(body).hexdigest() + '"'
        return cls(
            body=body,
            etag=etag,
            gitops_commit=gitops_commit,
            tree_hash=tree_hash,
            generated_at=generated_at,
            missing=resolution.missing,
        )


def render_body(
    *, resolution: Resolution, chart_path: str, gitops_commit: str, generated_at: datetime
) -> str:
    """Render the body in the versions-<env>.env format of access-node-compose."""
    lines = [
        "# Generated by access-node-compose-api from dome-gitops",
        f"# chart: {chart_path}",
        f"# gitops-commit: {gitops_commit}",
        f"# generated-at: {format_timestamp(generated_at)}",
    ]
    if resolution.missing:
        lines.append(f"# missing: {' '.join(resolution.missing)}")
    for key, image in resolution.images:
        if not _IMAGE_RE.fullmatch(image):
            raise ValueError(f"{key}: invalid image reference {image!r}")
        lines.append(f"{key}={image}")
    return "\n".join(lines) + "\n"
